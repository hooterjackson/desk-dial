"""Firmware C++11 gate for the shared, platform-neutral translation units.

The firmware is built by Arduino-ESP32 2.0.14 with GCC 8.4 in -std=gnu++11.
The host harness (MSVC) and light_tests (MSVC) cannot compile below C++14, so
code that is only valid in C++14/17 would pass on the PC and then break the
device build. This gate compiles every shared unit with the real ESP32-S3
xtensa g++ in gnu++11 mode, the same way PlatformIO does.

Checks, per unit:
1. ``-fsyntax-only`` with the firmware's C++ flags plus -Wall -Wextra
   -Wpedantic. Any error fails. Any diagnostic that names a C++14/17 feature
   ("only available with -std=c++14", "C++14 feature", ...) also fails, because
   GCC 8 reports several of those as warnings in gnu++11.
2. An -O0 object compile, then ``nm`` for undefined *data* symbols of the form
   ``Class::member``. In C++11 an odr-used ``static constexpr`` data member
   needs an out-of-class definition; without it the device link fails (or
   only works by accident of -Os). Rule: keep constant tables at namespace
   scope ``constexpr``.
3. A self-test proves the compiler really rejects a C++14 construct, so the
   gate can never pass vacuously.
4. C units: every generated knob font ``src/fonts/cc_font_*.c`` is compiled
   by the xtensa gcc in the firmware's C mode (-std=gnu99 plus the
   framework's C flags) with -Wall -Wextra -Wpedantic against the firmware
   lv_conf.h. Any output at all (error, warning or note) fails the unit.
5. Firmware source rules (1.0.0-cc5.2): no ``FastLED.addLeds<...>`` (a FastLED
   clockless controller brings back FastLED's own ESP32 RMT driver, whose
   unbounded wait hung the HMI task in 1.0.0-cc5.1), no other RMT user and no
   FastLED ESP32 driver option anywhere in ``src/`` (comments are ignored). A
   self-test proves the rules catch code and skip comments.

No USB, no device access, no PlatformIO. Exit status is non-zero on failure.

Extend SHARED_UNITS when a new platform-neutral .cpp is added (UNIT_INCLUDES
names the host shims a unit needs in place of ESP-IDF headers), and
HEADER_UNITS when a new header-only shared unit is added: its generated
translation unit must odr-use everything the header defines, so that the -O0
object and the nm check see it. C_UNIT_GLOBS picks up C units by pattern.
"""
from pathlib import Path
import re
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parent
WORK = ROOT.parent
FIRMWARE = WORK / 'firmware'
LIBDEPS = FIRMWARE / '.pio' / 'libdeps' / 'nanofoc_d'
TOOLCHAIN = WORK / 'platformio-core' / 'packages' / 'toolchain-xtensa-esp32s3' / 'bin'
GXX = TOOLCHAIN / 'xtensa-esp32s3-elf-g++.exe'
GCC = TOOLCHAIN / 'xtensa-esp32s3-elf-gcc.exe'
NM = TOOLCHAIN / 'xtensa-esp32s3-elf-nm.exe'

