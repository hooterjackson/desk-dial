# Firmware source rules checked over src/ (1.0.0-cc5.2, CONTROL_CENTER.md "LED transport"):
# (pattern, why). The RMT peripheral belongs to the bounded transport in cc_led_rmt.cpp; a
# FastLED clockless controller (FastLED.addLeds<CHIPSET, PIN, ...>) would bring back FastLED's
# own RMT driver and interrupt, whose unbounded wait hung the HMI task in 1.0.0-cc5.1.
FIRMWARE_SOURCE_RULES = [
    (re.compile(r'addLeds\s*<'), 'FastLED.addLeds<...> instantiates a FastLED clockless (RMT) controller; '
                                 'register a CCLedController with FastLED.addLeds(&controller, ...) instead'),
    (re.compile(r'\b(?:neopixelWrite|rmtInit|rmtWrite|Adafruit_NeoPixel)\b'),
     'another RMT user next to the LED transport (cc_led_rmt.cpp owns the RMT peripheral)'),
    (re.compile(r'\bFASTLED_RMT_BUILTIN_DRIVER\b|\bFASTLED_ESP32_I2S\b'),
     'a FastLED ESP32 driver option; the LED transport is cc_led_rmt.cpp'),
]
FIRMWARE_SOURCE_GLOBS = ['*.cpp', '*.h', '*.c']

INCLUDES = [FIRMWARE / 'src', FIRMWARE / 'include']
# Third-party headers are system includes so their own warnings do not drown
# out ours; they are still parsed in gnu++11.
SYSTEM_INCLUDES = [LIBDEPS / 'lvgl', LIBDEPS / 'ArduinoJson' / 'src']
# lv_conf.h is found through the firmware include/ directory (PlatformIO uses
# LV_CONF_PATH to point at the same file).
DEFINES = ['LV_CONF_INCLUDE_SIMPLE', 'LV_LVGL_H_INCLUDE_SIMPLE']
# CXXFLAGS/CCFLAGS from framework-arduinoespressif32 tools/platformio-build-esp32s3.py
# that affect language acceptance, plus diagnostics.
FIRMWARE_FLAGS = ['-std=gnu++11', '-fexceptions', '-fno-rtti', '-mlongcalls',
                  '-Wno-unused-parameter', '-Wno-sign-compare', '-Wwrite-strings']
DIAGNOSTIC_FLAGS = ['-Wall', '-Wextra', '-Wpedantic']
# C units (generated fonts), relative to src/, compiled with the framework's C flags.
C_UNIT_GLOBS = ['fonts/cc_font_*.c']
C_FIRMWARE_FLAGS = ['-std=gnu99', '-Os', '-mlongcalls', '-ffunction-sections', '-fdata-sections',
                    '-fno-jump-tables', '-fstrict-volatile-bitfields', '-Wno-old-style-declaration']

NEWER_STANDARD = re.compile(
    r'only available with -std=(?:c|gnu)\+\+(?:1y|14|1z|17|2a|20)'
    r'|-std=(?:c|gnu)\+\+(?:1y|14|1z|17|2a|20)'
    r'|C\+\+(?:1y|14|1z|17|2a|20)\b')
# Undefined data symbols that are allowed (none today).
ODR_ALLOW: set = set()


def base_command(extra_system_includes=()):
    command = [str(GXX)] + FIRMWARE_FLAGS + DIAGNOSTIC_FLAGS
    command += [f'-D{define}' for define in DEFINES]
    command += [f'-I{path}' for path in INCLUDES]
    for path in list(SYSTEM_INCLUDES) + list(extra_system_includes):
        command += ['-isystem', str(path)]
    return command


def run(command):
    result = subprocess.run(command, capture_output=True, text=True, encoding='utf-8', errors='replace')
    return result.returncode, (result.stdout + result.stderr).strip()


def self_test(scratch: Path) -> bool:
    # Relaxed constexpr (C++14) must be rejected in gnu++11.
    probe = scratch / 'cxx14_probe.cpp'
    probe.write_text('constexpr int twice(int x) { int y = x; y *= 2; return y; }\n'
                     'static_assert(twice(2) == 4, "");\n', encoding='utf-8')
    code, output = run([str(GXX), '-std=gnu++11', '-fsyntax-only', str(probe)])
    rejected = code != 0 or bool(NEWER_STANDARD.search(output))
    print(f'self-test: C++14 relaxed constexpr {"rejected" if rejected else "ACCEPTED (gate broken)"}')
    return rejected


def check_unit(unit: str, scratch: Path, label: str = '') -> bool:
    source = FIRMWARE / 'src' / unit
    label = label or unit
    if not source.is_file():
        print(f'FAIL {label}: missing {source}')
        return False
    extra = UNIT_INCLUDES.get(unit, ())
    for path in extra:
        if not Path(path).is_dir():
            print(f'FAIL {label}: host shim directory missing: {path}')
            return False
    ok = True
    code, output = run(base_command(extra) + ['-fsyntax-only', str(source)])
    newer = [line for line in output.splitlines() if NEWER_STANDARD.search(line)]
    if output:
        print(output)
    if code != 0:
        print(f'FAIL {label}: gnu++11 syntax errors (exit {code})')
        ok = False
    if newer:
        print(f'FAIL {label}: {len(newer)} diagnostic(s) name a C++14/17 feature')
        ok = False
    if not ok:
        return False
    obj = scratch / (Path(unit).stem + '.o')
    code, output = run(base_command(extra) + ['-O0', '-c', str(source), '-o', str(obj)])
    if code != 0:
        print(output)
        print(f'FAIL {label}: -O0 object compile failed (exit {code})')
        return False
    code, output = run([str(NM), '-C', '--undefined-only', str(obj)])
    if code != 0:
        print(output)
        print(f'FAIL {label}: nm failed (exit {code})')
        return False
    suspects = []
    for line in output.splitlines():
        name = line.split(None, 1)[-1].strip() if line.strip() else ''
        if ('::' in name and '(' not in name and not name.startswith(('std::', 'vtable for', 'typeinfo', '__cxxabi'))
                and name not in ODR_ALLOW):
            suspects.append(name)
    if suspects:
        print(f'FAIL {label}: undefined class data members (odr-used static constexpr?): {", ".join(sorted(set(suspects)))}')
        return False
    print(f'PASS {label}')
    return True


def check_header_unit(header: str, scratch: Path) -> bool:
    """HEADER_UNITS[header], written to `scratch`, checked like a shared unit."""
    if not (FIRMWARE / 'src' / header).is_file():
        print(f'FAIL {header}: missing {FIRMWARE / "src" / header}')
        return False
    tu = scratch / (Path(header).stem + '_gate.cpp')
    tu.write_text(HEADER_UNITS[header], encoding='utf-8', newline='\n')
    return check_unit(str(tu), scratch, label=f'{header} (via {tu.name})')


def strip_comments(text: str) -> str:
    """C/C++ source without // and /* */ comments (string and character literals kept)."""
    out, i, n = [], 0, len(text)
    while i < n:
        c = text[i]
        if c in '"\'':
            j = i + 1
            while j < n and text[j] != c and text[j] != '\n':
                j += 2 if text[j] == '\\' else 1
            out.append(text[i:j + 1])
            i = j + 1
        elif text.startswith('//', i):
            j = text.find('\n', i)
            i = n if j < 0 else j
        elif text.startswith('/*', i):
            j = text.find('*/', i + 2)
            out.append('\n' * text.count('\n', i, n if j < 0 else j))   # keep line numbers
            i = n if j < 0 else j + 2
        else:
            out.append(c)
            i += 1
    return ''.join(out)


def check_firmware_sources() -> bool:
    """FIRMWARE_SOURCE_RULES over every firmware source file (comments ignored)."""
    ok, checked = True, 0
    for pattern in FIRMWARE_SOURCE_GLOBS:
        for path in sorted((FIRMWARE / 'src').rglob(pattern)):
            checked += 1
            code = strip_comments(path.read_text(encoding='utf-8', errors='replace'))
            for rule, why in FIRMWARE_SOURCE_RULES:
                for match in rule.finditer(code):
                    line = code.count('\n', 0, match.start()) + 1
                    print(f'FAIL {path.relative_to(FIRMWARE).as_posix()}:{line}: {match.group(0)!r}: {why}')
                    ok = False
    print(f'{"PASS" if ok else "FAIL"} firmware source rules ({len(FIRMWARE_SOURCE_RULES)} rules over {checked} files '
          'in src/): no FastLED clockless controller, no other RMT user')
    return ok


def firmware_rules_self_test() -> bool:
    """The rules must catch a real use and ignore the same text in comments."""
    code = strip_comments('// FastLED.addLeds<WS2811, 38, RGB>(leds, 60);\n/* rmtInit(1) */\n'
                          'const char* s = "// not a comment";\nFastLED.addLeds<WS2811, 38, RGB>(leds, 60);\n')
    hits = [m.group(0) for rule, _ in FIRMWARE_SOURCE_RULES for m in rule.finditer(code)]
    ok = hits == ['addLeds<'] and '"// not a comment"' in code
    print(f'self-test: firmware source rules {"catch code and skip comments" if ok else "BROKEN"}')
    return ok


def c_command() -> list:
    command = [str(GCC)] + C_FIRMWARE_FLAGS + DIAGNOSTIC_FLAGS + [f'-D{define}' for define in DEFINES]
    command += [f'-I{path}' for path in INCLUDES]
    for path in SYSTEM_INCLUDES:
        command += ['-isystem', str(path)]
    return command


def c_self_test(scratch: Path) -> bool:
    # A warning-only C unit must be caught by the "any output fails" rule.
    probe = scratch / 'c_probe.c'
    probe.write_text('#include "lvgl.h"\nint cc_probe(void) { int unused; return 0; }\n', encoding='utf-8')
    code, output = run(c_command() + ['-fsyntax-only', str(probe)])
    caught = code == 0 and 'unused' in output
    print(f'self-test: C warning {"reported" if caught else "NOT reported (gate broken)"}')
    return caught


def c_units() -> list:
    return sorted(str(path.relative_to(FIRMWARE / 'src')).replace('\\', '/')
                  for pattern in C_UNIT_GLOBS for path in (FIRMWARE / 'src').glob(pattern))


def check_c_unit(unit: str) -> bool:
    source = FIRMWARE / 'src' / unit
    code, output = run(c_command() + ['-fsyntax-only', str(source)])
    if output:
        print(output)
    if code != 0 or output:
        print(f'FAIL {unit}: gnu99 compile {"failed (exit " + str(code) + ")" if code else "produced output"}')
        return False
    print(f'PASS {unit} (C, gnu99, silent)')
    return True


def main() -> int:
    for tool in (GXX, GCC, NM):
        if not tool.is_file():
            print(f'FAIL: toolchain not found: {tool}')
            return 2
    if not (LIBDEPS / 'lvgl' / 'lvgl.h').is_file() or not (LIBDEPS / 'ArduinoJson' / 'src').is_dir():
        print(f'FAIL: PlatformIO library dependencies missing under {LIBDEPS}')
        return 2
    print(f'C++11 gate: {GXX.name} ({" ".join(FIRMWARE_FLAGS[:1])}) over {len(SHARED_UNITS)} shared unit(s) '
          f'and {len(HEADER_UNITS)} header-only unit(s)')
    with tempfile.TemporaryDirectory(prefix='cpp11-gate-') as temp:
        scratch = Path(temp)
        if not self_test(scratch):
            return 1
        results = [check_unit(unit, scratch) for unit in SHARED_UNITS]
        results += [check_header_unit(header, scratch) for header in HEADER_UNITS]
        passed = sum(results)
        print(f'C++11 gate: {passed}/{len(results)} unit(s) passed')
        units = c_units()
        if not units:
            print(f'FAIL: no C units match {C_UNIT_GLOBS} under {FIRMWARE / "src"}')
            return 1
        print(f'C unit gate: {GCC.name} ({C_FIRMWARE_FLAGS[0]}) over {len(units)} unit(s)')
        if not c_self_test(scratch):
            return 1
    c_results = [check_c_unit(unit) for unit in units]
    print(f'C unit gate: {sum(c_results)}/{len(c_results)} unit(s) passed')
    rules = firmware_rules_self_test() and check_firmware_sources()
    return 0 if all(results) and all(c_results) and rules else 1


if __name__ == '__main__':
    sys.exit(main())
